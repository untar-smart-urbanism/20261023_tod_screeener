import { properties, validation, rows } from "../data.js";
import { likelyDuplicates } from "../../analysis/dedupe.js";
import { inspectCollection, completeness } from "../../analysis/inspect.js";

// Data-quality assessment: eight dimensions, each with a test and a result (or "unknown").
export default function Quality() {
  const r = inspectCollection(properties);
  const dupes = likelyDuplicates(rows);
  const priced = completeness(properties.features.map((f) => f.properties.asking_price_idr));
  const DIMENSIONS = [
    ["Accuracy", "Compare 10 random records with imagery or a site visit", "Not applicable — synthetic points"],
    ["Completeness", "Nulls per field", `${priced.present} of ${priced.total} asking prices present (${Math.round(priced.share * 100)}%)`],
    ["Currency", "Min/max date", r.dateRange ? `Listings dated ${r.dateRange[0]} to ${r.dateRange[1]}` : "unknown"],
    ["Consistency", "Units, categories, duplicate IDs", `Units in field names (_m2, _idr); ${validation.duplicates.length} duplicate positions; ${dupes.length} likely duplicate listings (same type + area within 11 m)${dupes.length ? ": " + dupes.map((g) => g.join(" = ")).join("; ") : ""}`],
    ["Granularity", "Unit of observation", "Point per listing (no parcel boundaries)"],
    ["Lineage", "Transformations in the method log", "Generated by course team; no transformations"],
    ["Licensing", "Use, store, share?", "Teaching use only"],
    ["Bias", "Coverage across districts and housing types", "unknown — synthetic sample"],
  ];
  return (
    <section>
      <p className="kicker">Data-quality page</p>
      <h1>Eight questions before you trust a dataset</h1>
      <div className="stats">
        <div><b>{r.features}</b> features</div>
        <div><b>{Object.keys(r.fields).length}</b> fields</div>
        <div><b>{r.geometryTypes.join(", ")}</b> geometry</div>
        <div><b>{r.crs}</b></div>
      </div>
      <table>
        <thead><tr><th>Field</th><th>Types</th><th>Nulls</th></tr></thead>
        <tbody>
          {Object.entries(r.fields).map(([k, v]) => (
            <tr key={k}><td><code>{k}</code></td><td>{v.types.join(" / ")}</td><td>{v.nulls}</td></tr>
          ))}
        </tbody>
      </table>
      <h3>Assessment</h3>
      <table>
        <thead><tr><th>Dimension</th><th>Test</th><th>Result</th></tr></thead>
        <tbody>
          {DIMENSIONS.map(([d, t, res]) => <tr key={d}><td>{d}</td><td>{t}</td><td>{res}</td></tr>)}
        </tbody>
      </table>
      <p className="note">Full assessment: <code>docs/DATA_QUALITY.md</code>. Write "unknown" when a dimension cannot be assessed.</p>
    </section>
  );
}
